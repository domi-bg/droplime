#!/usr/bin/env python3
"""Synthesizes the demo's soundtrack and UI sounds from scratch (no samples, no third-party audio).

    python3 scripts/make-music.py public

writes public/music.wav (calm electronic loop, 100 BPM, 50 s) and public/sfx/{tick,click,pop,chime}.wav.
Everything here is original and generated by this script, so it can be used freely under the repo's license.
Needs numpy.
"""
import sys
import wave
from pathlib import Path

import numpy as np

SR = 44100
BPM = 100
BEAT = 60 / BPM
BAR = 4 * BEAT
LENGTH = 50.0
rng = np.random.default_rng(7)


def hz(midi):
    return 440.0 * 2 ** ((midi - 69) / 12)


def t_axis(seconds):
    return np.arange(int(seconds * SR)) / SR


def env(n, attack, release, total=None):
    total = total or n / SR
    t = np.arange(n) / SR
    e = np.minimum(1, t / max(attack, 1e-4))
    e *= np.clip((total - t) / max(release, 1e-4), 0, 1)
    return e


def add(buf, start, sig, pan=0.0):
    i = int(start * SR)
    if i >= buf.shape[1]:
        return
    sig = sig[: buf.shape[1] - i]
    buf[0, i:i + len(sig)] += sig * np.sqrt(0.5 * (1 - pan))
    buf[1, i:i + len(sig)] += sig * np.sqrt(0.5 * (1 + pan))


def pad_voice(freq, seconds):
    t = t_axis(seconds)
    sig = np.zeros_like(t)
    for detune in (-0.12, 0.0, 0.12):
        f = freq * 2 ** (detune / 12)
        for h in range(1, 7):
            sig += np.sin(2 * np.pi * f * h * t + rng.uniform(0, 6.28)) / (h ** 1.6)
    return sig / 6


def pluck(freq, seconds=1.2, decay=0.32):
    t = t_axis(seconds)
    sig = np.sin(2 * np.pi * freq * t) + 0.35 * np.sin(2 * np.pi * freq * 2 * t) + 0.1 * np.sin(2 * np.pi * freq * 3 * t)
    return sig * np.exp(-t / decay) * np.minimum(1, t / 0.004)


def reverb(x, seconds=2.6, mix=0.32, seed=1):
    r = np.random.default_rng(seed)
    n = int(seconds * SR)
    t = np.arange(n) / SR
    ir = r.standard_normal(n) * np.exp(-t * 6.9 / seconds)
    ir[: int(0.012 * SR)] = 0
    ir /= np.sqrt(np.sum(ir ** 2))
    size = 1 << int(np.ceil(np.log2(len(x) + n)))
    wet = np.fft.irfft(np.fft.rfft(x, size) * np.fft.rfft(ir, size), size)[: len(x)]
    return x * (1 - mix) + wet * mix * 1.4


def write(path, stereo):
    stereo = np.asarray(stereo)
    if stereo.ndim == 1:
        stereo = np.vstack([stereo, stereo])
    peak = np.max(np.abs(stereo))
    if peak > 0.98:
        stereo = stereo * 0.98 / peak
    data = (stereo.T * 32767).astype('<i2')
    path.parent.mkdir(parents=True, exist_ok=True)
    with wave.open(str(path), 'wb') as w:
        w.setnchannels(2)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(data.tobytes())


def music():
    n = int((LENGTH + 3) * SR)
    pads = np.zeros((2, n))
    keys = np.zeros((2, n))
    bass = np.zeros((2, n))
    perc = np.zeros((2, n))

    # D major, calm: Dmaj9 – Bm7 – Gmaj7 – A6sus, two bars each.
    chords = [
        (50, [62, 66, 69, 73, 76]),
        (47, [62, 66, 69, 71, 74]),
        (43, [62, 66, 67, 71, 74]),
        (45, [61, 64, 66, 69, 71]),
    ]
    span = 2 * BAR
    bars = int(np.ceil(LENGTH / BAR)) + 1
    for k in range(0, bars, 2):
        start = k * BAR
        root, notes = chords[(k // 2) % len(chords)]
        length = span + 1.6
        for j, m in enumerate(notes[:4]):
            v = pad_voice(hz(m), length) * env(int(length * SR), 1.1, 1.6) * 0.09
            add(pads, start, v, pan=(-0.5, 0.4, -0.2, 0.5)[j])
        b = t_axis(span + 0.4)
        for half in range(4):
            seg = t_axis(BAR / 2 + 0.3)
            tone = np.sin(2 * np.pi * hz(root) * seg) + 0.25 * np.sin(2 * np.pi * hz(root) * 2 * seg)
            add(bass, start + half * BAR / 2, tone * env(len(seg), 0.04, 0.35) * 0.16)
        del b

        # Arpeggio in eighths, from 4 s on (after the intro), thinning out in the outro.
        pattern = [0, 2, 1, 3, 4, 2, 3, 1, 0, 2, 4, 3, 1, 3, 2, 4]
        for e in range(16):
            at = start + e * BEAT / 2
            if at < 4.0 or at > LENGTH - 1.5:
                continue
            if at > 44 and e % 2:
                continue
            m = notes[pattern[e]] + 12
            vel = 0.11 if e % 4 == 0 else 0.075
            add(keys, at, pluck(hz(m)) * vel, pan=0.35 if e % 2 else -0.35)

    # Soft percussion between the scenes' first drag and the outro.
    beats = int(LENGTH / BEAT)
    for b in range(beats):
        at = b * BEAT
        if 7.2 <= at < 44:
            if b % 2 == 0:
                t = t_axis(0.35)
                f = 50 + 70 * np.exp(-t / 0.03)
                kick = np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t / 0.12)
                add(perc, at, kick * 0.22)
            t = t_axis(0.08)
            noise = rng.standard_normal(len(t))
            hat = np.diff(noise, prepend=0) * np.exp(-t / 0.018)
            add(perc, at + BEAT / 2, hat * 0.014, pan=0.3)

    # Delay on the keys (dotted eighth).
    d = int(0.75 * BEAT * SR)
    for c in range(2):
        echo = np.zeros(n)
        echo[d:] = keys[1 - c, :-d] * 0.32
        echo[2 * d:] += keys[c, :-2 * d] * 0.12
        keys[c] += echo

    mix = pads + keys + bass + perc
    for c in range(2):
        mix[c] = reverb(mix[c], mix=0.3, seed=c + 1)

    mix = mix[:, : int(LENGTH * SR)]
    t = t_axis(LENGTH)
    fade = np.minimum(1, t / 1.5) * np.clip((LENGTH - t) / 3.5, 0, 1)
    mix *= fade
    return mix / np.max(np.abs(mix)) * 0.7


def sfx():
    out = {}
    t = t_axis(0.25)
    out['tick'] = (np.sin(2 * np.pi * 2600 * t) * np.exp(-t / 0.012) * 0.5
                   + rng.standard_normal(len(t)) * np.exp(-t / 0.004) * 0.15)
    t = t_axis(0.12)
    click = np.diff(rng.standard_normal(len(t)), prepend=0) * np.exp(-t / 0.003) * 0.25
    out['click'] = click + np.sin(2 * np.pi * 1500 * t) * np.exp(-t / 0.006) * 0.2
    t = t_axis(0.4)
    f = 300 + 650 * np.exp(-t / 0.025)
    out['pop'] = (np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t / 0.07) * np.minimum(1, t / 0.002) * 0.7
                  + np.sin(2 * np.pi * 120 * t) * np.exp(-t / 0.05) * 0.25)
    t = t_axis(1.8)
    chime = sum(a * np.sin(2 * np.pi * f * t) * np.exp(-t / dcy)
                for f, a, dcy in [(hz(88), 0.5, 0.9), (hz(95), 0.3, 0.7), (hz(88) * 2.76, 0.08, 0.25), (hz(100), 0.15, 0.5)])
    out['chime'] = reverb(chime * np.minimum(1, t / 0.003) * 0.6, seconds=1.4, mix=0.35)
    return out


if __name__ == '__main__':
    base = Path(sys.argv[1] if len(sys.argv) > 1 else 'public')
    write(base / 'music.wav', music())
    for name, sig in sfx().items():
        write(base / 'sfx' / f'{name}.wav', sig)
    print('wrote', base / 'music.wav', 'and', base / 'sfx')
